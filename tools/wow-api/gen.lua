-- Build a luacheck read_globals table of the WoW Forever client's API from
-- Ketho/BlizzardInterfaceResources (branch "forever"). Run by update.sh:
--
--   luajit tools/wow-api/gen.lua <dir> <sha> <version> <build> <interface>
--
-- <dir> holds GlobalAPI.lua, LuaEnum.lua, FrameXML.lua, Frames.lua and
-- Mixins.lua from that upstream commit. Writes the table to stdout, sorted, so
-- the same input always gives the same output. Dotted names become nested
-- `fields` (so luacheck checks C_Timer.After, Enum.PowerType.ComboPoints);
-- leaf names allow any sub-field.
local dir, sha, version, build, interface = unpack(arg)
if not interface then
    io.stderr:write("usage: luajit gen.lua <dir> <sha> <version> <build> <interface>\n")
    os.exit(2)
end

local root = {}
local function add(path)
    local node = root
    for part in path:gmatch("[^%.]+") do
        node[part] = node[part] or {}
        node = node[part]
    end
end

local function readfile(name)
    local f = assert(io.open(dir .. "/" .. name, "rb"))
    local s = f:read("*a")
    f:close()
    return s
end

-- string lists: local X = { "Name", "C_Foo.Bar", ... }
local count = 0
for _, name in ipairs({ "GlobalAPI", "FrameXML", "Frames", "Mixins" }) do
    for s in readfile(name .. ".lua"):gmatch('"([^"]+)"') do
        if s:match("^[%a_][%w_]*[%w_%.]*$") then add(s); count = count + 1 end
    end
end
assert(count > 1000, "suspiciously few names (" .. count .. ") - bad download?")

-- LuaEnum.lua assigns the global Enum (and friends); load it as data only.
local chunk = assert(loadstring(readfile("LuaEnum.lua"), "LuaEnum.lua"))
local env = {}
setfenv(chunk, env)
chunk()
assert(type(env.Enum) == "table", "LuaEnum.lua defined no Enum table")
local function addtable(prefix, t)
    for k, v in pairs(t) do
        if type(k) == "string" then
            add(prefix .. "." .. k)
            if type(v) == "table" then addtable(prefix .. "." .. k, v) end
        end
    end
end
for g, v in pairs(env) do
    add(g)
    if type(v) == "table" then addtable(g, v) end
end

local out = {
    "-- GENERATED by tools/wow-api/gen.lua - do not edit, do not commit (git-ignored).",
    "-- Source: https://github.com/Ketho/BlizzardInterfaceResources/tree/" .. sha,
    ("-- WoW Forever %s build %s, interface %s"):format(version, build, interface),
    "return {",
}
local function key(k) return k:match("^[%a_][%w_]*$") and k or ("[%q]"):format(k) end
local function emit(node, indent)
    local keys = {}
    for k in pairs(node) do keys[#keys + 1] = k end
    table.sort(keys)
    for _, k in ipairs(keys) do
        if next(node[k]) then
            out[#out + 1] = indent .. key(k) .. " = { fields = {"
            emit(node[k], indent .. "  ")
            out[#out + 1] = indent .. "} },"
        else
            out[#out + 1] = indent .. ("%q,"):format(k)
        end
    end
end
emit(root, "  ")
out[#out + 1] = "}"
io.write(table.concat(out, "\n"), "\n")
